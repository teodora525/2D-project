template<size_t N>
std::vector<unsigned char> decodePixels(const PixelRun(&runs)[N]) {
    std::vector<unsigned char> pixels;
    size_t count = 0;
    for (const auto& run : runs) count += run.count;
    pixels.reserve(count * 4);
    for (const auto& run : runs) for (unsigned int i = 0; i < run.count; ++i) {
        pixels.push_back(run.r); pixels.push_back(run.g);
        pixels.push_back(run.b); pixels.push_back(run.a);
    }
    return pixels;
}
